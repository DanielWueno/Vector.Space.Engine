using Reyma.VectorSpace.Engine.Microservice.Infrastructure;
using Reyma.VectorSpace.Engine.Microservice.Infrastructure.Resumen;

namespace Reyma.VectorSpace.Engine.Microservice.Tests.Motor;

/// <summary>Regla determinista de 1.27: un positivo y un negativo por patron, mas configuracion y validacion.</summary>
public sealed class FiltroPrevioDeResumenTests
{
    private static readonly FiltroPrevioDeResumen PorDefecto = new(new FiltroPrevioOptions());

    private const string Metodo = "public void Guardar(Silos s) { if (s.Kilos > 0) Repositorio.Guardar(s); }";

    [Theory]
    [InlineData("ReyOneWeb/Reyma.Entidades.Produccion/Silos.designer.cs")]
    [InlineData("ReyOneWeb/Trafico/Form1.Designer.cs")]
    [InlineData("src/Modelos/Cliente.g.cs")]
    [InlineData("src/Modelos/Cliente.generated.cs")]
    [InlineData("src/Properties/AssemblyInfo.cs")]
    [InlineData("AssemblyInfo.cs")]
    [InlineData("ReyOneWeb/Reyma.Datos.Trafico/Reyma.Datos.Trafico.csproj")]
    [InlineData("web/package.json")]
    [InlineData("config/servicios.XML")]
    [InlineData("ReyOneWeb/ReyOneWeb/Trafico/RepocitorioReportes/RptBono.cs")]
    [InlineData("ReyOneWeb/ReyOneWeb/Trafico/RepocitorioReportes/RptRendimientoMonitoreo.aspx.designer.cs")]
    [InlineData(@"ReyOneWeb\ReyOneWeb\Trafico\RepocitorioReportes\RptVehiculosGeoTab.cs")]
    public void ExcluyePorRuta(string ruta) =>
        Assert.Equal("ruta", PorDefecto.Motivo(ruta, "Method", Metodo));

    [Theory]
    [InlineData("ReyOneWeb/Reyma.Entidades.Produccion/Silos.cs")]
    [InlineData("src/Modelos/MyAssemblyInfo.cs")]
    [InlineData("src/Modelos/Designer.cs")]
    [InlineData("src/Modelos/Catalog.cs")]
    [InlineData("docs/reglas.md")]
    [InlineData("ReyOneWeb/ReyOneWeb/Trafico/RepocitorioReportes/RptNewGastos.aspx.cs")]
    [InlineData("ReyOneWeb/ReyOneWeb/Trafico/Procesos/RptBono.cs")]
    [InlineData("ReyOneWeb/ReyOneWeb/Trafico/JS/jsPlanesRutasUrbanos.js")]
    public void NoExcluyeRutasDeNegocioParecidas(string ruta) =>
        Assert.Null(PorDefecto.Motivo(ruta, "Method", Metodo));

    [Fact]
    public void ExcluyeConstructoresPeroNoMetodosNiClases()
    {
        const string ruta = "src/Entidades/RegistroEventos.cs";
        Assert.Equal("tipo", PorDefecto.Motivo(ruta, "Constructor", "public RegistroEventos() { Detalle = new(); }"));
        Assert.Null(PorDefecto.Motivo(ruta, "Method", Metodo));
        Assert.Null(PorDefecto.Motivo(ruta, "Class", "public partial class CatalogoMovimientosPrenomina : WFMaestro"));
        Assert.Null(PorDefecto.Motivo(ruta, null, Metodo));
    }

    [Theory]
    [InlineData("public string MotivoCancelacion { get; set; }")]
    [InlineData("/// <summary>\n        /// Llave primaria.\n        /// </summary>\n        public int Pk_Calculo_Prenomina { get; set; }")]
    [InlineData("[Required]\npublic string Nombre {get;set;}")]
    [InlineData("public DateTime Fecha { get; private set; }")]
    [InlineData("public IList<Detalle> Detalles { get; init; } = new List<Detalle>();")]
    [InlineData("public int Id { get; }")]
    public void ExcluyeUnaPropiedadAutomaticaDeUnaLinea(string contenido) =>
        Assert.Equal("propiedad-automatica", PorDefecto.Motivo("src/Entidades/Viaje.cs", "Property", contenido));

    [Theory]
    // Grupo de propiedades de una entidad (Silos, CompraDirecta en la muestra): ambos jueces vieron negocio.
    [InlineData("public IDSilos Id {get;set;}\npublic Planta Planta {get;set;}\npublic string Clave_Corta {get;set;}")]
    // Propiedad calculada en una linea: puede ser una regla de negocio.
    [InlineData("public bool EstaVencido => FechaVencimiento < DateTime.Today;")]
    [InlineData("public decimal Total { get => Cantidad * Precio; }")]
    // Accesores con cuerpo.
    [InlineData("public bool InsertaViajesPedidos\n{\n    get { return this._insertaViajesPedidos; }\n    set { this._insertaViajesPedidos = value; }\n}")]
    public void NoExcluyePropiedadesConMasDeUnaDeclaracionOConLogica(string contenido) =>
        Assert.Null(PorDefecto.Motivo("src/Entidades/Silos.cs", "Property", contenido));

    [Fact]
    public void ExcluyeUnaCabeceraAutoGeneradaSoloEnLasPrimerasCincoLineas()
    {
        const string ruta = "src/Servicios/Cliente.cs";
        var cabecera = "//------\n// <auto-generated>\n//     Generado por una herramienta.\n// </auto-generated>\n//------\npublic class Cliente { }";
        var tarde = string.Concat(Enumerable.Repeat("// linea\n", 6)) + "// <auto-generated>\npublic class Cliente { }";

        Assert.Equal("auto-generado", PorDefecto.Motivo(ruta, "Class", cabecera));
        Assert.Null(PorDefecto.Motivo(ruta, "Class", tarde));
    }

    [Fact]
    public void DeshabilitadoNoExcluyeNada()
    {
        var filtro = new FiltroPrevioDeResumen(new FiltroPrevioOptions { Habilitado = false });
        Assert.Null(filtro.Motivo("App.csproj", "Constructor", "public int Id { get; set; }"));
    }

    [Fact]
    public void ConfigurarPatronesReemplazaLaListaPorDefectoEntera()
    {
        var filtro = new FiltroPrevioDeResumen(new FiltroPrevioOptions { PatronesDeRuta = [@"(?i)\.sql$"], TiposDeChunk = ["Interface"] });

        Assert.Equal("ruta", filtro.Motivo("db/procs.SQL", "SqlProcedure", "CREATE PROCEDURE p AS SELECT 1"));
        Assert.Null(filtro.Motivo("App.csproj", "PlainTextWindow", "<Project />"));
        Assert.Null(filtro.Motivo("src/A.cs", "Constructor", "public A() { }"));
        Assert.Equal("tipo", filtro.Motivo("src/IA.cs", "Interface", "public interface IA { }"));
    }

    [Fact]
    public void ModeloEIdentidadDistinguenVersionYReglas()
    {
        Assert.Equal("filtro-previo:v1", PorDefecto.Modelo);
        Assert.Equal(PorDefecto.Identidad, new FiltroPrevioDeResumen(new FiltroPrevioOptions()).Identidad);
        Assert.NotEqual(PorDefecto.Identidad, new FiltroPrevioDeResumen(new FiltroPrevioOptions { TiposDeChunk = [] }).Identidad);
        Assert.Equal("filtro-previo:v2", new FiltroPrevioDeResumen(new FiltroPrevioOptions { Version = 2 }).Modelo);
    }

    [Fact]
    public void LaConfiguracionPorDefectoEsValidaYLaInvalidaSeExplica()
    {
        Assert.Null(FiltroPrevioDeResumen.ErrorDeConfiguracion(new FiltroPrevioOptions()));
        Assert.Contains("expresion regular invalida", FiltroPrevioDeResumen.ErrorDeConfiguracion(new FiltroPrevioOptions { PatronesDeRuta = ["("] }));
        Assert.Contains("vacios", FiltroPrevioDeResumen.ErrorDeConfiguracion(new FiltroPrevioOptions { PatronesDeRuta = [" "] }));
        Assert.Contains("Version", FiltroPrevioDeResumen.ErrorDeConfiguracion(new FiltroPrevioOptions { Version = 0 }));
        // 'Field' figura en la ficha, pero ChunkType no lo tiene: los campos viajan en el chunk Class.
        var error = FiltroPrevioDeResumen.ErrorDeConfiguracion(new FiltroPrevioOptions { TiposDeChunk = ["Field"] });
        Assert.Contains("Field", error);
        Assert.Contains("Constructor", error);
    }
}
